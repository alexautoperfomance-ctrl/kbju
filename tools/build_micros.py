def mix(spec):
    v=blank()
    for part in spec.split(','):
        n,g=part.split(':'); g=float(g)
        if n not in U: raise SystemExit('нет USDA для '+n)
        for i,x in enumerate(U[n]):
            if x is not None: v[i]+=x*g/100
    return v
def kc(spec): return sum(BY[p.split(':')[0]]['k']*float(p.split(':')[1])/100 for p in spec.split(','))
