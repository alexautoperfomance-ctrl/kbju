    if c in('dairy','dairyfix') or re.search(r'молок|кефир|йогурт|ряженк|сметан',n): return 2,15,1
    if re.search(r'овсян|хлопья|отруб|мюсли|гранол',n): return 15 if re.search(r'сух|хлопья|отруб|мюсли',n) else 4,3,4
