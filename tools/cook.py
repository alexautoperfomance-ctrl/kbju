def group(cat,name=''):
    import re
    if re.search(r'кур|индей|утк|гус|перепел|цесар|бройлер',name): return 'poultry'
    if cat in('meat',): return 'meat'
    if cat in('fish','fishready'): return 'fish'
    if cat=='veg': return 'veg'
    if cat=='egg': return 'egg'
    return 'other'
METHOD={'отвар':'boil','вар':'boil','жар':'fry','туш':'stew','запеч':'bake','гриль':'grill','гриле':'grill','пару':'steam'}
def method_of(suffix):
    for k,v in METHOD.items():
        if k in suffix: return v
    return None
def cooked100(raw,cat,name,meth):
    """raw: dict k,p,f,c на 100 г сырого → на 100 г готового (выход, вытапливание жира, впитанное масло)"""
    g=group(cat,name); y=YIELD[g].get(meth,1.0); oil=OIL.get(g,{}).get(meth,0)
    f=raw['f']*FATRET.get(meth,1)+oil*.98
    out={'p':raw['p']/y,'f':f/y,'c':raw['c']/y}
    out['k']=raw['k']/y-(raw['f']*(1-FATRET.get(meth,1)))*9/y+oil*.98*9/y
    return out,y,oil
